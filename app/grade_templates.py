"""Internal grade chemistry templates.

The plant's grade database stores a permitted MIN/MAX band per element. This module
serves the band midpoint as a selectable starting chemistry, so an operator can begin
from a grade the mill already rolls instead of the model's own defaults.

The workbook is not in the repository; models/grade_templates.json is the shipped
artefact, regenerated by app/build_grade_templates.py.
"""

import json
import os

import streamlit as st

APP_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(APP_DIR)
BUNDLE_PATH = os.path.join(ROOT, "models", "grade_templates.json")

MANUAL = "— manual entry —"
SIMULATOR = "— simulator chemistry —"


@st.cache_data(show_spinner=False)
def load():
    try:
        with open(BUNDLE_PATH, "r", encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return {}


def names():
    return list(load().get("grades", {}).keys())


def get(name):
    return load().get("grades", {}).get(name)


def chemistry(name):
    """Median band midpoint as app feature keys (Chem_C, Chem_Mn, ...)."""
    record = get(name)
    if not record:
        return {}
    return {f"Chem_{element}": value for element, value in record.get("median", {}).items()}


def band(name):
    """(min, max) per element, for the caption beside the picker."""
    record = get(name)
    if not record:
        return {}, {}
    return record.get("min", {}), record.get("max", {})
