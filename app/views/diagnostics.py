"""
Model Diagnostics, Whitebox Constitutive Formulas & Knowledge Graph View.
Displays multi-model leaderboards, bootstrap confidence intervals,
explicit NLR physics equations, and embedded interactive Graphify architecture.
"""

import os
import streamlit as st
import streamlit.components.v1 as components
import pandas as pd
import plotly.express as px
from model_loader import get_leaderboard_data, get_ci_data, get_nlr_formulas, REPO_ROOT


def render_diagnostics_view():
    st.markdown("### Model Diagnostics & Domain Knowledge Base")
    st.markdown(
        "Audit validation metrics evaluated strictly on **unseen melt heats** (zero data leakage), "
        "inspect whitebox constitutive equations, and explore the complete code architecture graph."
    )

    mill_type = st.radio("Select Product Line", ["Plate", "HRC"], horizontal=True, key="diag_mill")

    tab_lead, tab_ci, tab_nlr, tab_graph = st.tabs([
        "📊 Model Leaderboard", "🎯 95% Bootstrap CIs", "🔬 Whitebox NLR Formulas", "🕸️ Architecture Knowledge Graph"
    ])

    with tab_lead:
        st.subheader(f"{mill_type} Validation Leaderboard (Held-Out Melt Heats)")
        df_lead = get_leaderboard_data(mill_type)
        if not df_lead.empty:
            st.dataframe(df_lead, use_container_width=True)
            if "Val_R2" in df_lead.columns and "Target" in df_lead.columns:
                fig = px.bar(
                    df_lead, x="Target", y="Val_R2", color="Model" if "Model" in df_lead.columns else None,
                    barmode="group", title="Validation R² across Target Properties",
                    template="plotly_dark", height=400
                )
                st.plotly_chart(fig, use_container_width=True)
        else:
            st.info("Leaderboard data not available.")

    with tab_ci:
        st.subheader(f"{mill_type} 100-Iteration Heat-Level Bootstrap Confidence Intervals")
        st.markdown(
            "Empirical 95% confidence intervals generated by resampling test heats with replacement ($B=100$) "
            "to demonstrate statistical stability against melt variability."
        )
        df_ci = get_ci_data(mill_type)
        if not df_ci.empty:
            st.dataframe(df_ci, use_container_width=True)
        else:
            st.info("Bootstrap confidence interval reports not available.")

    with tab_nlr:
        st.subheader("Whitebox Non-Linear Constitutive Metallurgical Formulas")
        st.markdown(
            "Explicit physical formulas fitted via Levenberg-Marquardt / Trust Region Reflective optimization. "
            "These equations provide non-blackbox, human-interpretable baselines grounded in dislocation density, "
            "Pickering solid solution strengthening, and Hall-Petch grain size proxies."
        )
        formulas_txt = get_nlr_formulas(mill_type)
        st.code(formulas_txt, language="text")

    with tab_graph:
        st.subheader("Interactive System Architecture Graph")
        st.markdown(
            "Live interactive topological map of all 26 Python pipeline modules, classes, and cross-cutting dependencies, "
            "generated by Graphify."
        )
        graph_html_path = os.path.join(REPO_ROOT, "graphify-out", "graph.html")
        if os.path.exists(graph_html_path):
            with open(graph_html_path, "r", encoding="utf-8") as f:
                html_content = f.read()
            components.html(html_content, height=650, scrolling=True)
        else:
            st.info("graphify-out/graph.html not found.")
